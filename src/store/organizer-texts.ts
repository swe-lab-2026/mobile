const ALL: Record<Lang, Ox> = { ru, kk, en };

export function useOx() {
  const { lang, t } = useLanguage();
  return { ox: ALL[lang], t, lang };
}

/** "dd.mm.yyyy at HH:MM" for a wall-clock form value, or the placeholder. */
export function wallTimeLabel(value: string, ox: Ox): string {
  if (!value) return ox.selectDateTime;
  const [date, time] = value.split('T');
  const [year, month, day] = date.split('-');
  return `${day}.${month}.${year} ${ox.at} ${time}`;
}
